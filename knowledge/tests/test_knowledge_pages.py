def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


class LibraryFactsTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)

    def test_text_facts_come_from_the_extracted_header(self):
        write(self.root / "doc_a.txt", "# id: doc_a\n# pages: 41 in the original; references from page 35 on removed\n"
              "# page headers/footers: 3 repeated lines removed\n# literature-search syntax: 0 lines removed\n"
              "# Generated by ...\n\n--- page 1 ---\n" + "word " * 40 + "\n--- page 2 ---\nFig. 1\n")
        facts = library.text_facts("doc_a", split_words=True, extracted_dir=self.root)
        self.assertEqual((facts.pages, facts.references_from, facts.header_lines, facts.search_lines, facts.thin_pages,
                          facts.split_words), (41, 35, 3, 0, 1, True))
        self.assertIsNone(library.text_facts("missing", extracted_dir=self.root))

    def test_rows_status_and_the_curators_list(self):
        catalog = load_catalog()
        first, second = catalog[0], catalog[1]
        write(self.root / "store" / "info.json", json.dumps({"created": "2026-10-22T19:01:20+00:00", "chunks": 9,
                                                              "chunks_per_document": {first.id: 9}}))
        write(self.root / "extracted" / f"{first.id}.txt", "# pages: 2 in the original\n--- page 1 ---\n" + "x" * 90)
        manifest = write(self.root / "manifest.csv",
                         "file_id,title,url,folder,filename,type,status,licence,date_downloaded,notes\n"
                         f"G01,First,u,01_guidelines,{Path(first.file).name},guideline,downloaded,not shown,,\n"
                         "G99,Behind a login,u,01_guidelines,g99.pdf,guideline,needs manual download,not shown,,\n"
                         "R01,A reference,u,06_professional_knowledge,r01.pdf,reference,downloaded,CC BY 4.0,,\n"
                         "D01,A dataset,u,05_datasets,d01.zip,dataset,downloaded,CC0,,\n")
        rows = library.library_rows([first, second], manifest, self.root / "store", self.root / "extracted")
        self.assertEqual([(row.title, row.status) for row in rows],
                         [(first.title, library.SEARCHED), (second.title, library.NOT_IN_INDEX),
                          ("Behind a login", library.LINK_ONLY), ("A reference", library.NOT_CATALOGUED)])
        self.assertEqual((rows[0].passages, rows[3].licence, rows[2].licence), (9, "CC BY 4.0", None))
        version = library.library_version(self.root / "store")
        queue = library.curator_queue(rows, [], version)
        self.assertEqual([item["what"] for item in queue],
                         ["not_extracted", "link_only", "search_quality_due"])
        later = [{"recorded_at": "2026-10-23T08:00:00+00:00"}]
        self.assertNotIn("search_quality_due", [item["what"] for item in library.curator_queue(rows, later, version)])

    def test_why_an_item_may_need_a_curator(self):
        item = KnowledgeItem(knowledge_id="k", statement="s", domain="prosthetics", topic="knee", source_id="d",
                             citation="c", date="2024", source_type="professional_knowledge")
        self.assertEqual(item_reasons(item), ["no_rule", "population_not_set", "practice"])


class KnowledgePageTests(RouteTestCase):
    def text(self, url, lang="en"):
        self.client.set_cookie("lang", lang)
        resp = self.client.get(url)
        self.assertEqual(resp.status_code, 200, url)
        return resp.get_data(as_text=True)

    def test_sources_list_every_catalogued_document_with_its_facts(self):
        html = self.text("/knowledge")
        page = visible_text(html)
        for shown in ("Source library and ingestion", "From document to search", "Needs a curator", "Add a source",
                      "Licence", "Status"):
            self.assertIn(shown, page)
        for doc in load_catalog():
            self.assertIn(doc.title, page)
        self.assertIn('<a href="/knowledge" aria-current="true">', html)
        self.assertIn('<span class="ui-part">/ Knowledge layer</span>', html)
        self.assertIn("الطبقة المعرفية", visible_text(self.text("/knowledge", "ar")))

    def test_sources_narrowed_by_kind_and_words(self):
        protocols = visible_text(self.text("/knowledge?kind=protocol"))
        manuals = [doc.title for doc in load_catalog() if doc.source_type == "professional_knowledge"]
        self.assertTrue(manuals and all(title not in protocols for title in manuals))
        found = visible_text(self.text("/knowledge?q=no-such-words-anywhere"))
        self.assertIn("No document matches.", found)

    def test_evidence_is_read_only_and_names_the_rule(self):
        html = self.text("/knowledge/evidence?item=va_dod_ll_17_microprocessor_knee")
        page = visible_text(html)
        for shown in ("Evidence and curation", "Weak for", "Set by the owner's rule R2", "The owner's rule table",
                      "Read-only: the evidence fields are set only by the owner's rule table"):
            self.assertIn(shown, page)
        self.assertNotIn("<form", html.split("<main", 1)[1])  # nothing on the page writes a value
        practice = visible_text(self.text("/knowledge/evidence?reason=practice"))
        self.assertIn("icrc_", practice)
        self.assertNotIn("va_dod_ll_17_microprocessor_knee", practice.split("Knowledge items", 1)[1].split("The owner", 1)[0])

    def test_graph_shows_the_clinic_rules_and_what_is_not_built(self):
        page = visible_text(self.text("/knowledge/graph"))
        for shown in ("Clinic rules", "Draft rule, awaiting the owner's approval", "Open wound or infection",
                      "Arabic terms", "Design knowledge graph", "Case library", "Not built yet"):
            self.assertIn(shown, page)


class SearchQualityRecordTests(unittest.TestCase):
    def test_an_evaluation_run_records_itself_when_asked(self):
        from knowledge import evaluate

        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        path = Path(tmp.name) / "runs.jsonl"
        outcome = type("Outcome", (), {"query": {"group": "English"}, "rank": 1, "results": []})()
        with patch.object(results.config, "QUALITY_RESULTS_PATH", path), \
                patch.object(evaluate, "load_queries", return_value=[{"group": "English"}]), \
                patch.object(evaluate, "run", return_value=[outcome]), patch.object(evaluate, "report"), \
                patch("builtins.print"):
            evaluate.main(store=object(), record=True)
        [run] = results.read_runs(path)
        self.assertEqual((run["kind"], run["queries"], run["hit_at_1"], run["hit_at_5"]),
                         (results.SEARCH_QUALITY, 1, 1, 1))


